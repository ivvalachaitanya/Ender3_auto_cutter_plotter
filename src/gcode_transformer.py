"""
G-code Transformer & PolyCut Fiducial Compensation Module

Allows loading G-code generated by PolyCut, JScut, or Inkscape and applying:
1. Camera ArUco/Manual Fiducial Scan 2D Affine Transformation (Scale, Rotation, Translation).
2. Camera & Drag Knife toolhead offset compensation.
"""

import json
import logging
import os
import re
from typing import List, Optional, Tuple, Union
import numpy as np

logger = logging.getLogger(__name__)


class GCodeTransformer:
    """Parses G-code files and applies 2D Affine Transformation matrix for fiducial alignment."""

    def __init__(self, matrix: Optional[np.ndarray] = None):
        """
        Initialize G-code Transformer.

        :param matrix: 2x3 or 3x3 2D Affine Transformation numpy matrix
        """
        self.matrix = matrix

    @staticmethod
    def load_affine_matrix(matrix_file_path: str) -> Optional[np.ndarray]:
        """Load 2D Affine Matrix from affine_matrix.json file."""
        if os.path.isfile(matrix_file_path):
            try:
                with open(matrix_file_path, "r", encoding="utf-8") as f:
                    data = json.load(f)
                    mat = data.get("matrix")
                    if mat is not None:
                        return np.array(mat, dtype=np.float64)
            except Exception as e:
                logger.error("Failed to load affine matrix from %s: %s", matrix_file_path, e)
        return None

    def transform_point(self, x: float, y: float) -> Tuple[float, float]:
        """Apply 2D Affine Matrix to (x, y) point."""
        if self.matrix is None:
            return x, y

        M = self.matrix
        x_new = float(M[0, 0] * x + M[0, 1] * y + M[0, 2])
        y_new = float(M[1, 0] * x + M[1, 1] * y + M[1, 2])
        return x_new, y_new

    def transform_gcode_file(self, input_path: str, output_path: str, matrix: Optional[np.ndarray] = None) -> bool:
        """
        Read G-code file (from PolyCut, JScut, Inkscape), apply 2D Affine Transformation, and save.

        :param input_path: Path to raw input G-code file
        :param output_path: Path to output compensated G-code file
        :param matrix: 2x3 affine matrix (optional override)
        :return: True if successfully transformed
        """
        if matrix is not None:
            self.matrix = matrix

        if not os.path.isfile(input_path):
            logger.error("Input G-code file '%s' not found.", input_path)
            return False

        if self.matrix is None:
            logger.warning("No affine matrix provided. G-code will pass through untransformed.")

        try:
            with open(input_path, "r", encoding="utf-8") as f:
                lines = f.readlines()

            transformed_lines = []
            curr_x, curr_y = 0.0, 0.0
            is_absolute = True

            x_regex = re.compile(r"([XY])([+-]?[0-9.]+)")

            for line in lines:
                line_str = line.strip()

                # Check positioning mode G90 (Absolute) vs G91 (Relative)
                if "G90" in line_str:
                    is_absolute = True
                    transformed_lines.append(line)
                    continue
                elif "G91" in line_str:
                    is_absolute = False
                    transformed_lines.append(line)
                    continue

                # Skip non-motion comments / blank lines
                if not line_str or line_str.startswith(";") or line_str.startswith("("):
                    transformed_lines.append(line)
                    continue

                # Check motion commands (G0, G1, G2, G3)
                if line_str.startswith("G0") or line_str.startswith("G1") or line_str.startswith("G2") or line_str.startswith("G3"):
                    # Find X and Y values
                    matches = dict(x_regex.findall(line_str))
                    if "X" in matches or "Y" in matches:
                        new_x = float(matches["X"]) if "X" in matches else curr_x
                        new_y = float(matches["Y"]) if "Y" in matches else curr_y

                        if is_absolute and self.matrix is not None:
                            tx, ty = self.transform_point(new_x, new_y)
                        else:
                            tx, ty = new_x, new_y

                        curr_x, curr_y = new_x, new_y

                        # Replace X and Y in the line string
                        new_line = line
                        if "X" in matches:
                            new_line = re.sub(r"X[+-]?[0-9.]+", f"X{tx:.4f}", new_line)
                        if "Y" in matches:
                            new_line = re.sub(r"Y[+-]?[0-9.]+", f"Y{ty:.4f}", new_line)

                        transformed_lines.append(new_line)
                        continue

                transformed_lines.append(line)

            with open(output_path, "w", encoding="utf-8") as f:
                f.writelines(transformed_lines)

            logger.info("Successfully transformed PolyCut/G-code file '%s' -> '%s'.", input_path, output_path)
            return True

        except Exception as e:
            logger.error("Failed to transform G-code file: %s", e)
            return False
